#pragma once

#include <memory>

#include "events/bus.hpp"

namespace pdr::events {

/// ШИНА ОДНОГО ОБРАЩЕНИЯ ВМЕСТЕ СО ВСЕМ, ЧТО НА НЕЙ СИДИТ.
///
/// Подписчик живёт ровно столько, сколько шина, а шина — сколько обращение.
/// Иначе получается обычная беда подписок: шина пережила подписчика и зовёт
/// его по указателю, которого больше нет. Здесь это невыразимо — и то и другое
/// лежит внутри одного объекта и умирает вместе с ним.
class Attachment {
public:
    Attachment(const Attachment&) = delete;
    Attachment& operator=(const Attachment&) = delete;

    virtual ~Attachment() = default;

    /// Шина, в которую публикует издатель. Подписчики на ней уже сидят.
    virtual Bus& Events() = 0;

protected:
    Attachment() = default;
};

/// КТО СЛУШАЕТ СОБЫТИЯ ЭТОГО ОБРАЩЕНИЯ — и куда он их записывает.
///
/// Порт существует ради одной вещи: подписчик обязан писать В ТУ ЖЕ
/// ТРАНЗАКЦИЮ, что и издатель. Иначе строку очереди и изменение, о котором она
/// рассказывает, разделяет момент, в который можно упасть, — и падение уносит
/// либо письмо без события, либо событие без письма. Сессия поэтому приходит
/// параметром: подписчик не берёт её сам и взять не может.
///
/// ИЗДАТЕЛЬ ПО-ПРЕЖНЕМУ НЕ ЗНАЕТ ПОДПИСЧИКОВ. Он публикует в шину; кто на ней
/// сидит, решает процесс, называя компонент в статическом конфиге. Контекст,
/// который публикует событие, не включает ни одного заголовка того, кто его
/// слушает, — и это проверяет scripts/check_layers.py.
///
/// Общей шины на процесс здесь быть не может: её подписчик писал бы в чужую
/// транзакцию или, что то же самое, ни в какую.
///
/// Тип сессии — параметр шаблона: реестр событий не знает ни про userver, ни
/// про Postgres и знать не должен. Связывает их адаптер, у которого сессия
/// настоящая.
template<class Session>
class Listeners {
public:
    Listeners(const Listeners&) = delete;
    Listeners& operator=(const Listeners&) = delete;

    virtual ~Listeners() = default;

    /// Собрать шину этого обращения и подписать на неё всех, кого положено.
    virtual std::unique_ptr<Attachment> Attach(Session& session) const = 0;

protected:
    Listeners() = default;
};

}  // namespace pdr::events
