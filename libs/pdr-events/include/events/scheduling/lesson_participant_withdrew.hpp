namespace pdr::events::scheduling {

/// УЧАСТНИК ВЫШЕЛ С ЗАНЯТИЯ. Занятие при этом осталось.
///
/// Отдельное событие, а не отмена с пометкой, и это главное различие всей
/// задачи PDR-SCHED-08. Следствия у них разные и расходятся сразу:
///
/// * отмена касается всех — комнату не открывают, напоминания забирают,
///   репетитор освобождает час;
/// * выход касается одного — занятие состоится, остальные придут, и час никуда
///   не девается.
///
/// Подписчик, различающий их полем внутри одного события, однажды забудет
/// проверить поле; подписчик, не подписанный на второе событие, просто не
/// получит его — и это видно в коде, а не в проде.
///
/// Сегодня выход не случается ни разу: участник ровно один, а последнего
/// вывести нельзя — это отмена. Событие заведено заранее, потому что заводить
/// его вместе с группами значило бы менять в тот день ещё и реестр событий.
struct LessonParticipantWithdrew final {
    static constexpr std::string_view kType = "scheduling.lesson_participant_withdrew";
    static constexpr int kVersion = 1;

    Envelope envelope;
    core::LessonId lesson;

    /// Кто вышел. Не «кого это касается»: остальных участников это событие не
    /// касается вовсе — их занятие не изменилось.
    core::PersonId participant;

    /// Кто нажал. Выйти может и не сам участник: опекун выводит подопечного,
    /// репетитор — того, кто перестал ходить.
    core::PersonId actor;

    /// Удержано с ЭТОГО участия. Ровно по той же политике, что и при отмене:
    /// поздний выход стоит столько же, сколько поздняя отмена, — и это не
    /// «заодно», а причина, по которой окно и политика считаются отдельно
    /// (PDR-SCHED-07).
    core::Money retained;
    RetentionReason reason{RetentionReason::kInsideFreeWindow};
};

}  // namespace pdr::events::scheduling
