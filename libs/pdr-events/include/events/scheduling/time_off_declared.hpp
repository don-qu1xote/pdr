namespace pdr::events::scheduling {

/// ЧЕЛОВЕКА НЕ БУДЕТ С ЭТОГО ПО ЭТО.
///
/// Издаётся ПЕРВЫМ действием — тем, в котором период только заведён и решение
/// по занятиям ещё не принято. Двух событий здесь не от избытка: «меня не
/// будет» и «вот что я сделал с занятиями» происходят в разное время, и
/// подписчики у них разные.
///
/// ОТРЕЗОК — В МОМЕНТАХ, ХОТЯ ЧЕЛОВЕК НАЗЫВАЛ ДАТЫ. Местная дата становится
/// моментом только по правилам зоны, и разбираться в них подписчику незачем:
/// издатель уже разобрался. Конец ИСКЛЮЧИТЕЛЬНЫЙ — полночь дня, следующего за
/// последним днём перерыва: «по четырнадцатое включительно» и «до пятнадцатого»
/// — одно и то же, и только второе не требует помнить про эту разницу.
///
/// ЗАЧЕМ ЭТО БИЛЛИНГУ. Автоплатёж внутри перерыва не срабатывает: списывать за
/// занятия, которых не будет, нельзя (PDR-BILL-05). Отрезок здесь именно затем,
/// чтобы биллинг мог приостановить списания, не спрашивая расписание ни о чём.
struct TimeOffDeclared final {
    static constexpr std::string_view kType = "scheduling.time_off_declared";
    static constexpr int kVersion = 1;

    Envelope envelope;
    core::TimeOffId time_off;

    /// Кого не будет. Не «репетитор» и не «ученик»: перерыв у человека, а какой
    /// стороной он стоит в занятии, видно из самого занятия.
    core::PersonId person;

    core::Instant from;
    core::Instant to;

    /// Причина, если названа. Пусто — обычный случай, а не недозаполненное поле.
    std::optional<TimeOffReason> reason;
};

}  // namespace pdr::events::scheduling
