#pragma once

#include <span>

#include "identity/application/policies/policy.hpp"

namespace pdr::identity::policies {

/// Права на расписание: записать, отменить, перенести, посмотреть и задать
/// часы работы.
///
/// Правило одно на три первых действия: СВОИМИ ЗАНЯТИЯМИ РАСПОРЯЖАЕТСЯ ТОТ, ЧЬИ
/// ОНИ. Репетитор — те, что ведёт; ученик — свои; опекун — своего подопечного.
/// Взрослый самостоятельный ученик распоряжается сам, и отдельного случая для
/// него не нужно: у него просто нет опекуна, а «свои» у него те же.
///
/// Владелец школы записывать и отменять за других НЕ МОЖЕТ. Это не упущение:
/// «владелец может всё» — самая дорогая строка в любой системе прав, потому что
/// после неё все остальные строки становятся необязательными. Расписание он
/// видит целиком — этого хватает, чтобы вести школу, и не хватает, чтобы за
/// кого-то отменить занятие.
///
/// ЧАСЫ РАБОТЫ — ПЯТОЕ ДЕЙСТВИЕ И САМОЕ УЗКОЕ: задать их вправе только сам
/// репетитор. «Когда я работаю» — утверждение о себе, и подставить его за
/// другого нельзя даже владельцу практики; смотреть их при этом вправе те же,
/// кто видит расписание.
class SchedulingPolicy final : public Policy {
public:
    SchedulingPolicy() = default;

    /// Действия, которые эта политика берёт на себя.
    static std::span<const Action> Actions() noexcept;

    PolicyDecision Decide(const Subject& subject,
                          Action action,
                          const Resource& resource) const override;
};

}  // namespace pdr::identity::policies
