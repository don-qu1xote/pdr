#pragma once

#include "core/types/ids.hpp"

namespace pdr::infrastructure::observe {

/// АРЕНДАТОР В КАЖДОЙ ЗАПИСИ, А НЕ В ТОЙ, ГДЕ ВСПОМНИЛИ.
///
/// Тег спана, а не поле записи: поставленный один раз, он достаётся всем
/// записям внутри области — включая те, что напишет адаптер, ничего про
/// арендатора не знающий. Модель построена на `tenant_id` целиком, и разбор
/// инцидента без него сводится к грепу по русским строкам.
///
/// Зовётся из одного места — `db::TenantContext::Open`, — и это то же самое
/// место, где арендатор объявляется базе. Забыть тег так же нечем, как забыть
/// объявление: единственный конструктор области закрыт.
///
/// Спана может не быть — вне сопрограммы userver его нет вовсе, — и тогда
/// функция молча ничего не делает. Это не потеря: записи там тоже нет.
void TagTenant(const core::TenantId& tenant);

/// КТО ПРИШЁЛ — там, где это становится известно, и больше нигде.
///
/// Зовётся формой запроса сразу после опознания (`ServedHandler::Serve`).
/// Ручке этого не поручают по той же причине, по какой ей не поручают выбор
/// статуса: одна поставит, другая забудет, и выяснится это по жалобе.
///
/// У ДВЕРИ АКТОРА НЕТ, и поля тоже нет. Входящий становится человеком по итогу
/// того самого запроса, которым входит, и `Caller::actor` у `DoorHandler` пуст
/// намеренно. Ноль в поле хуже отсутствия поля: по нему ищут и находят все
/// входы разом, приняв их за один.
void TagActor(const core::PersonId& actor);

}  // namespace pdr::infrastructure::observe
