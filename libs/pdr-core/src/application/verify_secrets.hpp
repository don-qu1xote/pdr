#pragma once

#include <span>
#include <string>
#include <vector>

#include "application/ports/secret_source.hpp"
#include "core/errors.hpp"
#include "core/secrets.hpp"

namespace pdr::application {

/// Что не так с секретами. Одна беда — одна строка, и в каждой названо ИМЯ.
///
/// «Проверьте конфигурацию» — сообщение, после которого человек открывает файл
/// и смотрит на него глазами. Здесь названа переменная, и открывать нечего.
struct SecretComplaint final {
    std::string name;
    std::string reason;

    friend bool operator==(const SecretComplaint&, const SecretComplaint&) = default;
};

/// ПРОВЕРКА СЕКРЕТОВ ПРИ СТАРТЕ. Отказ подниматься, а не запись в журнал.
///
/// Предупреждение в журнале означает, что сервис поднялся и работает «как будто
/// нормально»: подключение к базе не установилось, платежи не уходят, а метрика
/// зелёная, потому что процесс жив. Ловит это не мониторинг, а человек, у
/// которого не прошёл платёж.
///
/// Проверяется три вещи:
///
///   * каждый обязательный секрет ЕСТЬ — иначе названо его имя;
///   * каждый обязательный секрет НЕ ПУСТ — пустая строка это не значение;
///   * два секрета не делят одно значение. Названное в PDR-SEC-02 «подпись
///     одного и подпись другого» — частный случай: ключ, которым мы ходим к
///     провайдеру, и ключ, которым он подписывает нам ответ, обязаны
///     различаться, иначе утечка одного равна утечке обоих. Проверка шире
///     формулировки намеренно: два РАЗНЫХ секрета с одним значением — это
///     всегда вставленное дважды из буфера обмена.
///
/// Секрет, у которого в реестре стоит `awaits`, не спрашивается: читать его
/// пока некому. Требовать ключ от двери, которой нет, — верный способ приучить
/// человека вписывать «change-me».
///
/// Сравнение идёт перебором пар, а не через словарь: секретов при старте
/// единицы, и значения остаются в `SecretString`, вместо того чтобы лечь
/// открытым текстом в ключи контейнера.
core::Result<void> VerifySecrets(std::span<const core::SecretSpec> registry,
                                 const ports::SecretSource& source);

/// То же, но со списком всех бед сразу.
///
/// Останавливаться на первой — значит заставить человека, ставящего сервис,
/// узнавать о шести пропущенных переменных шестью запусками. Отказ при этом
/// остаётся отказом: `VerifySecrets` возвращает ошибку, как только список
/// непуст.
std::vector<SecretComplaint> InspectSecrets(std::span<const core::SecretSpec> registry,
                                            const ports::SecretSource& source);

}  // namespace pdr::application
