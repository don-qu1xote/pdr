namespace pdr::scheduling::ports {

/// ЧЕМ МЕСТНЫЕ ДАТЫ ОКАЗЫВАЮТСЯ В МОМЕНТАХ.
///
/// Порт УЗКИЙ ДО ОДНОГО ВОПРОСА, и это намеренно. Общий «дай правила зоны»
/// (`application::ports::TimeZoneRules`, о котором говорит
/// libs/pdr-core/src/core/types/local_time.hpp) в дереве не заведён, и заводить
/// его здесь не за чем: ему нужна вся база IANA значением — начальное смещение
/// и список переводов, — а здесь спрашивают одно: «какой отрезок моментов
/// занимают эти дни у этого человека».
///
/// ОТВЕЧАЕТ БАЗА, И ЭТО НЕ ОБХОД СЛОЁВ. Таблицы переводов часов у ядра нет
/// намеренно: домен собирается и проверяется без системы, поэтому
/// `core::ZoneOffsets` приходит к нему ЗНАЧЕНИЕМ. У Postgres эта таблица есть,
/// она обновляется вместе с ним, и превращение даты в момент — ровно та работа,
/// которую он умеет делать лучше нас. Домен от этого не узнаёт ничего: он
/// по-прежнему говорит датами, а моменты приходят к сценарию из-за порта.
///
/// ГРАНИЦЫ РАЗНЫЕ, И ЭТО ГЛАВНОЕ В ОТВЕТЕ. Человек говорит «с первого по
/// четырнадцатое включительно», а сравнивать занятия удобно с полуинтервалом:
/// `[первое 00:00, пятнадцатое 00:00)`. Обе формы правильны, и путают их
/// постоянно — поэтому превращение живёт в одном месте, а не в каждом вызове.
class LocalDays {
public:
    LocalDays(const LocalDays&) = delete;
    LocalDays& operator=(const LocalDays&) = delete;

    virtual ~LocalDays() = default;

    /// Полуинтервал моментов, которым являются местные дни `[from, to]` в этой
    /// зоне. Конец — полночь дня, следующего за `to`.
    virtual core::Result<core::TimeRange> Between(const core::Date& from,
                                                  const core::Date& to,
                                                  const core::TimeZone& zone) const = 0;

protected:
    LocalDays() = default;
};

}  // namespace pdr::scheduling::ports
