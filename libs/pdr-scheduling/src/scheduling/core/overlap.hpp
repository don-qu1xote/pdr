namespace pdr::scheduling {

/// ПЕРЕСЕКАЮТСЯ ЛИ ЗАНЯТИЯ С УЧЁТОМ ПЕРЕРЫВА.
///
/// БУФЕР — ЧАСТЬ ПРАВИЛА, А НЕ УКРАШЕНИЕ ИНТЕРФЕЙСА. Репетитору нужны пять
/// минут между занятиями: дойти, выдохнуть, открыть следующий конспект. Буфер,
/// живущий в слое показа, не мешает записать второе занятие вплотную — он лишь
/// не покажет этого; правило же обязано отказать.
///
/// Касание концами пересечением НЕ считается: занятие, начинающееся ровно тогда,
/// когда кончилось предыдущее, конфликтует с ним только при ненулевом буфере.
/// Расстояние РОВНО в буфер — уже не конфликт: «пять минут между занятиями»
/// значит, что пять минут достаточно.
bool Overlaps(const Lesson& first, const Lesson& second, core::Instant::Duration buffer) noexcept;

}  // namespace pdr::scheduling
