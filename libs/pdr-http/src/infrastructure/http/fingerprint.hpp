#pragma once

#include <string_view>

#include "core/idempotency.hpp"

namespace pdr::infrastructure::http {

/// Отпечаток тела запроса. Считает штатный `crypto::hash::Sha256` (ADR-0013):
/// своего перемешивания байтов в дереве нет и не будет.
///
/// Тело берётся как есть, байт в байт. Никакой нормализации JSON перед счётом:
/// «то же самое тело» здесь означает буквально то же самое, и клиент, который
/// переставил поля местами, прислал другой запрос. Нормализация выглядит
/// заботой, а на деле это правило, о котором клиент не знает: он повторяет то,
/// что послал, а не то, что мы решили считать эквивалентным.
pdr::http::RequestFingerprint FingerprintOf(std::string_view body);

}  // namespace pdr::infrastructure::http
