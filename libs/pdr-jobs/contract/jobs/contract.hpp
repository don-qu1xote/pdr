namespace pdr::jobs {

/// АРЕНДАТОР СИСТЕМЫ: от чьего имени идёт работа, не принадлежащая никому.
///
/// Уборка просроченных строк, сверка, пересчёт горизонта для всех сразу —
/// работа про площадку, а не про чей-то кабинет. Контракт при этом арендатора
/// требует, и требует не зря: след действия лежит в
/// `jobs_effect (tenant_id, job, effect_key)`.
///
/// Поэтому у площадки есть свой арендатор — одна строка в `identity_tenant`,
/// заведённая миграцией `V012__system_tenant.sql`. Значение объявлено ЗДЕСЬ и
/// один раз: две записи одного идентификатора расходятся, а расхождение
/// выглядит как «след не поставился». Почему так, а не признаком «работа
/// кластерная» у задания — docs/adr/0021-system-tenant-for-clusterwide-jobs.md.
///
/// Доступа к чужим данным он не даёт: это обычная строка под обычной политикой,
/// и из его области видны только его собственные строки.
core::TenantId SystemTenant();

/// Единица работы периодического задания: чьё это дело и чем оно опознаётся.
///
/// `key` — детерминированный ключ действия. Одна и та же работа обязана давать
/// один и тот же ключ у любого воркера и в любом прогоне: «напомнить о занятии
/// 7f3c… за час до начала» — это один ключ, сколько бы раз задание ни
/// просыпалось. По ключу механизм отличает «ещё не сделано» от «уже сделано», и
/// второй рассылки не случается.
///
/// Ключ, в который подмешано «сейчас», — это не ключ: он новый на каждом
/// прогоне, и идемпотентности не будет вовсе.
struct WorkItem final {
    core::TenantId tenant;
    std::string key;
};

/// Периодическое задание — то, что пишет контекст.
///
/// ЕДИНСТВЕННЫЙ заголовок контекста `jobs`, видимый соседям: остальное для них
/// не существует, и попытку включить внутренность ловит
/// `scripts/check_layers.py`. Блокировка, журнал прогонов и следы действий — не
/// его забота: контекст отвечает на два вопроса и больше ни на один.
class PeriodicJob {
public:
    PeriodicJob(const PeriodicJob&) = delete;
    PeriodicJob& operator=(const PeriodicJob&) = delete;

    virtual ~PeriodicJob() = default;

    /// Что нужно сделать на момент `now`.
    ///
    /// Только чтение. Побочных действий у планирования нет и быть не может:
    /// план строится заново каждым воркером, в том числе тем, который подхватил
    /// работу после потери блокировки, — планирование, которое успело что-то
    /// натворить, натворит это дважды.
    virtual std::vector<WorkItem> Plan(core::Instant now) = 0;

    /// Произвести действие. Механизм вызывает его не более одного раза на ключ
    /// во всём кластере — след уже поставлен к этому моменту.
    virtual void Perform(const WorkItem& item) = 0;

protected:
    PeriodicJob() = default;
};

}  // namespace pdr::jobs
