-- Выгрузка продуктового потока для анализа.
--
-- Идёт НЕ под ролью приложения: pdr_app без объявленного арендатора не видит ни
-- строки, и политика для выгрузки исключений не делает. Читать поток целиком
-- может только тот, кто и так может всё, — администратор кластера.
--
-- Это и есть настоящая причина, по которой поток обезличен: вопрос «растёт ли
-- доля высоких оценок» задаётся про всех сразу, и ответ на него не должен
-- требовать доступа ни к одному человеку
-- (docs/architecture/product-events.md).
--
-- Зовётся целью make product-events-export OUT=<файл>. Файл называет цель, а не
-- этот запрос: copy ... to stdout отдаёт поток клиенту, и права на запись нужны
-- тому, кто запустил psql, а не серверу базы. Серверный copy ... to '<файл>'
-- писал бы внутрь контейнера, и выгрузка оказалась бы там, где её никто не
-- ищет.

-- Идентификатор записи в выгрузку не идёт: он нужен базе, а не анализу. Всё
-- остальное идёт целиком — включая версию схемы, без которой поля старых
-- записей нечем разобрать.
copy (select tenant_id, type, version, actor_role, occurred_at, recorded_at, fields
        from observability_product_event
       order by recorded_at, id)
  to stdout with (format csv, header true);
