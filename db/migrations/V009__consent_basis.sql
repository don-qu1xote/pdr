-- На каком основании открыт доступ: опека или слово самого ученика.
--
-- ОПЕКА И НАБЛЮДЕНИЕ — ОДИН МЕХАНИЗМ. Репетиторы нужны не только школьникам:
-- языки, вуз, переподготовка — у такого ученика опекуна нет вовсе, и продукт не
-- должен делать вид, что он потерялся. Но доступ ему бывает нужен тот же самый:
-- супруг, тренер, работодатель, оплачивающий курс.
--
-- Поэтому здесь колонка, а не вторая таблица. Вторая таблица означала бы второй
-- набор уровней, второй отзыв и второй журнал — и через полгода они разошлись
-- бы (docs/adr/0020-adult-student-is-the-main-case.md).
alter table identity_guardian_consent add column basis text not null default 'guardianship';
alter table identity_guardian_consent add constraint identity_guardian_consent_basis_known
    check (basis in ('guardianship', 'named_by_student', 'pays_for_lessons'));
comment on column identity_guardian_consent.basis is 'Чем держится доступ: опекой, словом взрослого или оплатой. От основания зависит, что доступ может нести.';

-- ДЕНЬГИ НЕ ДАЮТ ПРАВА СМОТРЕТЬ, и это ограничение схемы, а не соглашение.
--
-- Работодатель оплачивает курс, ученик учится, а конспекты и записи занятий
-- плательщик не видит. Строку «плательщик с доступом к записям» база не примет
-- вовсе: не «мы такого не выдаём», а «выдать нечем».
alter table identity_guardian_consent add constraint identity_guardian_consent_money_is_not_sight
    check (basis <> 'pays_for_lessons' or scope = 'payments');

-- Умолчание нужно только строкам, заведённым до этой миграции: до неё доступ
-- бывал только опекунским. Новые строки называют основание явно — домен без
-- него согласия не собирает.
