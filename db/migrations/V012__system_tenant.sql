-- Арендатор системы: строка для работ, которые не принадлежат никому.
--
-- ЗАЧЕМ ОН ПОЯВИЛСЯ. `jobs::WorkItem` требует арендатора, и это сделано
-- намеренно: идемпотентность заданий лежит в `jobs_effect (tenant_id, job,
-- effect_key)`, а действие всегда чьё-то. Но кластерная работа арендатора не
-- имеет вовсе — уборка просроченных строк, сверка, пересчёт горизонта для всех
-- сразу. Обнаружилось это при первом настоящем задании, а не при написании
-- контракта (docs/architecture/first-service.md).
--
-- Выбран второй из двух выходов: отдельная строка вместо признака «работа
-- кластерная» у задания. Контракт не меняется, `jobs_effect` работает как
-- раньше, построчная защита не делает исключений. Почему не первый —
-- docs/adr/0021-system-tenant-for-clusterwide-jobs.md.
--
-- Строка одна на кластер и заводится схемой, а не кодом: задание, которое
-- заводит себе арендатора при первом прогоне, заводит его и на реплике, и
-- гонку между ними придётся чинить отдельно.

-- Объявление нужно на случай, когда миграции применяет роль, которой политика
-- писана: у identity_tenant стоит force row level security, и без объявленного
-- арендатора вставка не прошла бы. Объявление живёт до конца транзакции.
select set_config('pdr.tenant_id', '00000000-0000-4000-8000-000000000001', true);

insert into identity_tenant (tenant_id, name, tz)
values ('00000000-0000-4000-8000-000000000001', 'Система', 'UTC')
on conflict (tenant_id) do nothing;

comment on table identity_tenant is 'Арендатор: репетитор-одиночка или школа. Его собственный идентификатор и есть tenant_id, поэтому политика изоляции на этой таблице такая же, как на остальных. Одна строка служебная — арендатор системы для кластерных работ (docs/adr/0021-system-tenant-for-clusterwide-jobs.md).';
