-- @no-dto
-- Разборщик выполнить запрос не может: он меняет очередь, а образцовой строки
-- под неё у него нет.
--
-- ВЗЯТЬ ТО, ЧЕМУ НАСТАЛ СРОК, — сразу у всех практик. Запрос идёт под
-- объявленным разбором (notifications_declare_dispatch.sql): своей практики у
-- отправщика нет, а обход «по кругу, по одной» — это перебор, ради отсутствия
-- которого очередь и заводили.
--
-- `for update skip locked` — то, ради чего очередь лежит в Postgres. Вторая
-- реплика, проснувшаяся в ту же секунду, не ждёт первую и не берёт её строки:
-- занятые она пропускает и забирает следующие. Без `skip locked` реплики
-- выстроились бы в очередь друг за другом, и второй воркер не ускорял бы ничего.
--
-- ЗАХВАТ ПЕРЕЖИВАЕТ ТРАНЗАКЦИЮ. Блокировка строки снимается коммитом, а отправка
-- идёт уже снаружи — поэтому захват двигает `next_attempt_at` вперёд на срок
-- попытки. Умерший на отправке воркер не держит строку вечно: она снова
-- становится должной, когда срок вышел. Это и есть «не менее одного раза».
--
-- Внутренний список из базы не выезжает: он соединяется с самой таблицей, и
-- приводить его к тексту незачем — приведение нужно там, где строка уходит в
-- адаптер. Имена ему даны свои, чтобы соединение таблицы с самой собой читалось.
--
-- Попытка засчитывается здесь же, а не после неудачи: воркер, упавший молча,
-- иначе не тратил бы попыток вовсе и крутил бы одну строку до конца времён.
UPDATE notifications_outbox AS o
   SET attempts = o.attempts + 1,
       next_attempt_at = $2::timestamptz
  FROM (SELECT tenant_id AS locked_tenant_id, id AS locked_id
          FROM notifications_outbox
         WHERE state = 'pending'
           AND next_attempt_at <= $1::timestamptz
         ORDER BY next_attempt_at
         LIMIT $3::int
           FOR UPDATE SKIP LOCKED) AS due
 WHERE o.tenant_id = due.locked_tenant_id
   AND o.id = due.locked_id
RETURNING o.tenant_id::text AS tenant_id,
          o.id::text AS id,
          o.event_type,
          o.payload,
          o.dedup_key,
          o.created_at,
          o.attempts
