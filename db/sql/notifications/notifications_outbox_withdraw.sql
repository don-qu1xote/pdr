-- Строк не возвращает.
--
-- ОТОЗВАТЬ НЕОТПРАВЛЕННОЕ. Занятие отменили — напоминание «завтра в 17:00»
-- лежит в очереди и ждёт своего часа; отправить его после отмены значит соврать
-- человеку, а извиняться за это письмо будет репетитор.
--
-- Удаление, а не пометка: состояний у строки ровно три, и «отозвано» среди них
-- нет. Заводить четвёртое ради отзыва значит менять смысл колонки, о котором
-- договорились в миграции.
--
-- Ушедшего не трогаем: `sent` — это факт, что человеку написали, и стирать его
-- задним числом нечестно.
DELETE FROM notifications_outbox
 WHERE tenant_id = $1::uuid
   AND dedup_key = $2::text
   AND state = 'pending'
