-- Отправщику нужны строки всех практик сразу, и он единственный, кому они нужны:
-- практику он не выбирает, он спрашивает «чему настал срок». Политика
-- `notifications_outbox_dispatch` отвечает на это объявление и больше ни на что;
-- какие таблицы вправе его иметь, заперто списком в scripts/check_rls.py, а
-- почему так вообще — в docs/adr/0022-outbox-dispatch-across-tenants.md.
--
-- Параметр ОТДЕЛЬНЫЙ от `pdr.tenant_id` намеренно. Забытый арендатор обязан
-- оставаться пустым ответом, а не ключом ко всему: сравнение с NULL не подходит
-- ни к одной строке, и это свойство стоит дороже одной сэкономленной строчки.
--
-- Третий аргумент — true: объявление живёт до конца ТРАНЗАКЦИИ. С false оно
-- уехало бы в пул вместе с соединением, и следующий запрос человека увидел бы
-- очередь всех практик сразу.
