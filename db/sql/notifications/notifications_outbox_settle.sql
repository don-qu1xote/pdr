-- @no-dto
-- Строк не возвращает.
--
-- ЧЕМ КОНЧИЛАСЬ ПОПЫТКА. Три исхода на один запрос, и это не экономия: они
-- отличаются только значениями колонок, а не смыслом — «строка больше не должна»
-- (`sent`), «пробуем ещё, но позже» (`pending` с новым сроком), «больше не
-- пробуем» (`gave_up` с причиной). Три запроса разошлись бы на первой же правке.
--
-- Что именно сюда подставить, решает домен (notifications::RetryPolicy), а не
-- база: предел попыток и задержка — величины из динамического конфига, и считать
-- их в SQL значит спрятать их от теста.
--
-- Идёт под объявленным разбором, как и захват: отправщик по-прежнему без
-- практики, а строка адресуется первичным ключом — чужую он не заденет даже
-- ошибкой.
UPDATE notifications_outbox
   SET state = $3::text,
       next_attempt_at = $4::timestamptz,
       failed_reason = $5::text
 WHERE tenant_id = $1::uuid
   AND id = $2::uuid
