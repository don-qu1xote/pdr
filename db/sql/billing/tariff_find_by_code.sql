-- Запрос идёт в транзакции области, то есть на мастере: чтение доменных данных
-- живёт там, где объявлен арендатор. Реплика для него не годится — объявления
-- на ней не было бы.
--
-- Строк-структур у этого запроса нет и не будет, пока нет таблицы: tariffs в
-- схеме отсутствует, миграции завели только identity. Расхождение записано в
-- docs/architecture/context-map.md, раздел «Известные расхождения с кодом»;
-- запрет на порождение снимается вместе с миграцией тарифов.
SELECT price_minor_units,
       currency_code
  FROM tariffs
 WHERE code = $1
