-- Разобрать запрос разборщик не может: у образцовой строки в месте зоны
-- окажется не имя зоны, и `at time zone` отказывает прямо в разборе.
--
-- ПЕРЕВОДЫ ЧАСОВ СЧИТАЕТ БАЗА, И ЭТО НЕ ОБХОД СЛОЁВ.
--
-- Таблицы переводов у ядра нет намеренно: домен собирается и проверяется без
-- системы, поэтому core::ZoneOffsets приходит к нему ЗНАЧЕНИЕМ. У Postgres эта
-- таблица есть, она обновляется вместе с ним, и другого её источника в дереве
-- не заводится: своя копия базы IANA стоила бы того же ответа плюс обязанность
-- её обновлять.
--
-- КАК ЭТО РАБОТАЕТ. Смещение зоны в момент t — это разность между тем, что
-- показывают часы зоны, и самим моментом. Час за часом по отрезку смотрим, где
-- эта разность меняется: смена и есть перевод. Час — не приближение, а точная
-- сетка: переводы часов объявляются на целый час во всех зонах базы IANA.
--
-- Первая строка выборки — смещение, действующее В НАЧАЛЕ отрезка: `lag` у неё
-- пуст, и `is distinct from` пропускает её вперёд. Ею адаптер и заполняет
-- начальное смещение, остальными — переводы.
SELECT at,
       (EXTRACT(EPOCH FROM (at AT TIME ZONE $3) - (at AT TIME ZONE 'UTC')))::bigint AS offset_seconds
  FROM (SELECT hour AS at,
               (hour AT TIME ZONE $3) - (hour AT TIME ZONE 'UTC') AS shift,
               lag((hour AT TIME ZONE $3) - (hour AT TIME ZONE 'UTC'))
                   OVER (ORDER BY hour) AS before
          FROM generate_series($1::timestamptz, $2::timestamptz, interval '1 hour') AS hour
       ) AS walked
 WHERE before IS DISTINCT FROM shift
 ORDER BY at
