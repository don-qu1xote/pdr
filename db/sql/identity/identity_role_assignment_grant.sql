-- ПАЧКОЙ, А НЕ ПО СТРОКЕ В ЦИКЛЕ. Роли человеку выдают все сразу, и раньше это
-- было столько же обращений к базе, сколько ролей: заведение участника платило
-- за каждую роль отдельным круговым ходом внутри своей транзакции.
--
-- unnest разворачивает четыре массива в строки; массивы приезжают колонками —
-- ExecuteDecomposeBulk сам раскладывает по ним структуру (docs/architecture/queries.md,
-- «Вставка пачкой»). Отдельного составного типа для этого не нужно, значит и
-- схему под удобство C++ менять не пришлось.
--
-- Строк не возвращает; разобрать запрос разборщик к тому же не может —
-- образцовая роль не проходит identity_role_assignment_role_known.
INSERT INTO identity_role_assignment (tenant_id, id, person_id, role)
     SELECT *
       FROM unnest($1::uuid[], $2::uuid[], $3::uuid[], $4::text[])
