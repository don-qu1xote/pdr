-- Разобрать запрос разборщик не может: у образцовой строки в месте зоны
-- окажется не имя зоны, и `at time zone` отказывает прямо в разборе.
--
-- МЕСТНЫЕ ДНИ В МОМЕНТЫ — СЧИТАЕТ БАЗА, И ЭТО НЕ ОБХОД СЛОЁВ.
--
-- Таблицы переводов часов у ядра нет намеренно: домен собирается и проверяется
-- без системы, поэтому core::ZoneOffsets приходит к нему значением. У Postgres
-- эта таблица есть и обновляется вместе с ним — превращение даты в момент ровно
-- та работа, которую он делает лучше нас.
--
-- КОНЕЦ ИСКЛЮЧИТЕЛЬНЫЙ: полночь дня, следующего за последним днём перерыва.
-- Человек говорит «по четырнадцатое включительно», а сравнивать занятия удобно
-- полуинтервалом, и превращение одного в другое живёт здесь, а не в каждом
-- вызове.
SELECT ($1::date)::timestamp AT TIME ZONE $3 AS from_at,
       (($2::date) + 1)::timestamp AT TIME ZONE $3 AS to_at
