-- Подписка человека: способ называть занятия. Идёт по первичному ключу
-- (tenant_id, person_id) — своего индекса не просит.
--
-- Отпечатка здесь нет намеренно: он нужен только опознанию, и отдавать его
-- туда, где он не нужен, значит однажды записать его в журнал.
SELECT naming
  FROM scheduling_calendar_feed
 WHERE tenant_id = $1::uuid
   AND person_id = $2::uuid
