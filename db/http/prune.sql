-- Уборка просроченных ключей идемпотентности.
--
-- Ключ защищает от повтора ровно столько, сколько живёт: после срока клиент,
-- повторивший запрос, выполнит операцию заново — и это правильно, потому что
-- «повтор» через месяц означает намерение, а не оборванную связь.
--
-- Идёт под ролью МИГРАЦИЙ, а не приложения: у pdr_app нет права delete на этой
-- таблице, и это намеренно. Приложение, умеющее удалить ключ, умеет и обойти
-- собственную защиту от повтора одним лишним запросом.
--
-- Обходит все практики сразу, поэтому объявления арендатора здесь нет: уборка
-- не отвечает ни на чей вопрос о данных, она удаляет по сроку. Индекс
-- http_idempotency_key_by_age для этого и заведён.
--
-- Срок живёт в самой строке (expires_at), а не в этом файле: величина берётся
-- из PDR_IDEMPOTENCY в момент занятия ключа. Здесь только «что уже просрочено».
delete from http_idempotency_key where expires_at <= now();
